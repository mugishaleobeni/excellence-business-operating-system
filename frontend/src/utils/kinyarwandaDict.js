function translateSingleSegment(segment) {
  if (!segment || typeof segment !== 'string') return segment
  const trimmed = segment.trim().replace(/\s+/g, ' ')
  if (!trimmed) return segment

  const lower = trimmed.toLowerCase()
  const direct = KINYARWANDA_DICT[lower]
  if (direct) return direct

  for (const pat of DYNAMIC_PATTERNS) {
    const m = trimmed.match(pat.regex)
    if (m) {
      return pat.replace(...m)
    }
  }

  // Apply multi-word phrase replacements for compound UI headings/descriptions
  let result = trimmed
  for (const [enPhrase, rwPhrase] of PHRASE_REPLACEMENTS) {
    const rx = new RegExp(`\\b${enPhrase.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'gi')
    if (rx.test(result)) {
      result = result.replace(rx, rwPhrase)
    }
  }
  return result
}

/**
 * Translate an English UI string to Kinyarwanda when language === 'rw'.
 * Returns original string if not matched or if language === 'en'.
 */
export function translateToKinyarwanda(text) {
  if (!text || typeof text !== 'string') return text
  const trimmed = text.trim().replace(/\s+/g, ' ')
  if (!trimmed) return text

  const leading = text.match(/^\s*/)?.[0] || ''
  const trailing = text.match(/\s*$/)?.[0] || ''

  const lower = trimmed.toLowerCase()
  const direct = KINYARWANDA_DICT[lower]
  if (direct) {
    return `${leading}${direct}${trailing}`
  }

  for (const pat of DYNAMIC_PATTERNS) {
    const m = trimmed.match(pat.regex)
    if (m) {
      return `${leading}${pat.replace(...m)}${trailing}`
    }
  }

  // Handle separator-delimited compound labels ("A · B", "A — B", "A | B")
  for (const sep of [' · ', ' — ', ' | ']) {
    if (trimmed.includes(sep)) {
      const parts = trimmed.split(sep).map((p) => translateSingleSegment(p))
      return `${leading}${parts.join(sep)}${trailing}`
    }
  }

  const out = translateSingleSegment(trimmed)
  return `${leading}${out}${trailing}`
}
