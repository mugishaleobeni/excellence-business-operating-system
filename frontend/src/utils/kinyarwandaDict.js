/**
 * Translate an English UI string to Kinyarwanda when language === 'rw'.
 * Returns original string if not matched or if language === 'en'.
 */
export function translateToKinyarwanda(text) {
  if (!text || typeof text !== 'string') return text
  const trimmed = text.trim().replace(/\s+/g, ' ')
  if (!trimmed) return text

  const lower = trimmed.toLowerCase()
  const direct = KINYARWANDA_DICT[lower]
  if (direct) {
    const leading = text.match(/^\s*/)?.[0] || ''
    const trailing = text.match(/\s*$/)?.[0] || ''
    return `${leading}${direct}${trailing}`
  }

  for (const pat of DYNAMIC_PATTERNS) {
    const m = trimmed.match(pat.regex)
    if (m) {
      const leading = text.match(/^\s*/)?.[0] || ''
      const trailing = text.match(/\s*$/)?.[0] || ''
      return `${leading}${pat.replace(...m)}${trailing}`
    }
  }

  return text
}
