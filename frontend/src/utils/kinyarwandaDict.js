function translateSingleSegment(segment) {
  if (!segment || typeof segment !== 'string') return segment
  const trimmed = segment.trim().replace(/\s+/g, ' ')
  if (!trimmed) return segment

  // Strip optional trailing "(Optional)" or "(Required)" or required marker (" *") or colon (":")
  const optMatch = trimmed.match(/\s*\((Optional|Required)\)\s*(\*|:)?$/i)
  if (optMatch) {
    const optWord = optMatch[1].toLowerCase() === 'optional' ? '(Si ngombwa)' : '(Birakenewe)'
    const tailMark = optMatch[2] || ''
    const basePart = trimmed.slice(0, -optMatch[0].length).trim()
    const baseTrans = KINYARWANDA_DICT[basePart.toLowerCase()] || translateSingleSegment(basePart)
    return `${baseTrans} ${optWord}${tailMark}`
  }

  const suffixMatch = trimmed.match(/(\s*\*|:)$/)
  const suffix = suffixMatch ? suffixMatch[1] : ''
  const core = suffix ? trimmed.slice(0, -suffix.length).trim() : trimmed

  const lower = core.toLowerCase()
  const direct = KINYARWANDA_DICT[lower]
  if (direct) return `${direct}${suffix}`

  // Handle "Label: Value" strings (e.g. "Cashier: Alice", "Status: Active", "Opening Float: 50,000 RWF")
  const colonIdx = trimmed.indexOf(': ')
  if (colonIdx > 0 && colonIdx < 42) {
    const labelPart = trimmed.slice(0, colonIdx).trim()
    const valuePart = trimmed.slice(colonIdx + 2)
    const translatedLabel = KINYARWANDA_DICT[labelPart.toLowerCase()]
    if (translatedLabel) {
      const maybeVal = KINYARWANDA_DICT[valuePart.trim().toLowerCase()]
      return `${translatedLabel}: ${maybeVal || valuePart}`
    }
  }

  for (const pat of DYNAMIC_PATTERNS) {
    const m = trimmed.match(pat.regex)
    if (m) {
      return pat.replace(...m)
    }
  }

  // Apply multi-word phrase replacements for compound UI headings/descriptions
  let result = trimmed
  for (const [enPhrase, rwPhrase] of PHRASE_REPLACEMENTS) {
    const rx = new RegExp(`\\b${enPhrase.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'gi')
    if (rx.test(result)) {
      result = result.replace(rx, rwPhrase)
    }
  }
  return result
}

/**
 * Translate an English UI string to Kinyarwanda when language === 'rw'.
 * Returns original string if not matched or if language === 'en'.
 */
export function translateToKinyarwanda(text) {
  if (!text || typeof text !== 'string') return text
  const trimmed = text.trim().replace(/\s+/g, ' ')
  if (!trimmed) return text

  const leading = text.match(/^\s*/)?.[0] || ''
  const trailing = text.match(/\s*$/)?.[0] || ''

  const lower = trimmed.toLowerCase()
  const direct = KINYARWANDA_DICT[lower]
  if (direct) {
    return `${leading}${direct}${trailing}`
  }

  for (const pat of DYNAMIC_PATTERNS) {
    const m = trimmed.match(pat.regex)
    if (m) {
      return `${leading}${pat.replace(...m)}${trailing}`
    }
  }

  // Handle separator-delimited compound labels ("A · B", "A — B", "A | B", "A → B")
  for (const sep of [' · ', ' — ', ' | ', ' → ']) {
    if (trimmed.includes(sep)) {
      const parts = trimmed.split(sep).map((p) => translateSingleSegment(p))
      return `${leading}${parts.join(sep)}${trailing}`
    }
  }

  const out = translateSingleSegment(trimmed)
  return `${leading}${out}${trailing}`
}
